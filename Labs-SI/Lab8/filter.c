/*
 * Лабораторная работа 8. Программный фильтр - "сглаживатель" сигнала.
 *
 * Программа читает поток чисел со стандартного входа (stdin), сглаживает
 * его свёрткой с набором коэффициентов и пишет результат в стандартный
 * выход (stdout). Встраивается в конвейер:
 *
 *        ./gen | ./filter | ./osc
 *        ./gen | ./filter 6 | ./osc        (выбор набора коэффициентов)
 *
 * Свёртка:  f[i] = (k0*y[i] + k1*y[i+1] + ... + k(m-1)*y[i+m-1]) / S,
 * где S - сумма коэффициентов, m - число точек. Входные значения
 * хранятся в кольцевом буфере из m элементов, поэтому программа
 * работает с бесконечным потоком и не требует памяти под весь сигнал.
 *
 * Наборы коэффициентов (из файла PASCAL.txt):
 *   0 - Паскаль, 3 точки        1 2 1                     / 4
 *   1 - Паскаль, 5 точек        1 4 6 4 1                 / 16
 *   2 - Паскаль, 7 точек        1 6 15 20 15 6 1          / 64
 *   3 - Паскаль, 9 точек        1 8 28 56 70 56 28 8 1    / 256
 *   4 - Савицкий-Голей, 5 точек  -3 12 17 12 -3           / 35
 *   5 - Савицкий-Голей, 7 точек  -2 3 6 7 6 3 -2          / 21
 *   6 - Савицкий-Голей, 9 точек  -21 14 39 54 59 54 39 14 -21   / 231
 *   7 - Савицкий-Голей, 7 точек (4 степень) 5 -30 75 131 75 -30 5 / 231
 *   8 - Савицкий-Голей, 9 точек (4 степень)
 *                          15 -55 30 135 179 135 30 -55 15      / 429
 *
 * Параметры: ./filter [номер_набора [число_проходов]]
 * По умолчанию набор 3 (Паскаль, 9 точек), 1 проход. При нескольких
 * проходах сигнал сглаживается последовательно несколько раз.
 *
 * Сборка:  gcc -Wall -Wextra -std=c99 filter.c -o filter
 */
#include <stdio.h>
#include <stdlib.h>

#define MAXK    19              /* максимальное число коэффициентов */
#define NSETS   9
#define MAXPASS 10

typedef struct {
    const char *name;
    int n;                      /* число точек */
    int k[MAXK];                /* коэффициенты */
} KERNEL;

/* Таблица коэффициентов */
static const KERNEL kernels[NSETS] = {
    {"Паскаль, 3 точки",           3, {1, 2, 1}},
    {"Паскаль, 5 точек",           5, {1, 4, 6, 4, 1}},
    {"Паскаль, 7 точек",           7, {1, 6, 15, 20, 15, 6, 1}},
    {"Паскаль, 9 точек",           9, {1, 8, 28, 56, 70, 56, 28, 8, 1}},
    {"Савицкий-Голей, 5 точек",    5, {-3, 12, 17, 12, -3}},
    {"Савицкий-Голей, 7 точек",    7, {-2, 3, 6, 7, 6, 3, -2}},
    {"Савицкий-Голей, 9 точек",    9, {-21, 14, 39, 54, 59, 54, 39, 14, -21}},
    {"Савицкий-Голей, 7 точек, 4 ст.", 7, {5, -30, 75, 131, 75, -30, 5}},
    {"Савицкий-Голей, 9 точек, 4 ст.", 9, {15, -55, 30, 135, 179, 135, 30, -55, 15}},
};

/* Один фильтр: кольцевой буфер последних n значений */
typedef struct {
    const KERNEL *ker;
    double sum;                 /* сумма коэффициентов (нормировка) */
    double y[MAXK];             /* буфер */
    int pos;                    /* куда писать следующее значение */
    int filled;                 /* сколько значений уже в буфере */
} FILTER;

void filter_init(FILTER *f, const KERNEL *ker)
{
    f->ker = ker;
    f->sum = 0;
    for (int i = 0; i < ker->n; i++)
        f->sum += ker->k[i];
    f->pos = 0;
    f->filled = 0;
}

/* Подать на фильтр очередное значение x.
   Возвращает 1 и записывает результат в *res, когда буфер заполнен. */
int filter_step(FILTER *f, double x, double *res)
{
    int n = f->ker->n;
    f->y[f->pos] = x;
    f->pos = (f->pos + 1) % n;
    if (f->filled < n) {
        f->filled++;
        if (f->filled < n)
            return 0;
    }
    /* свёртка: самое старое значение лежит в y[pos] */
    double s = 0;
    for (int i = 0; i < n; i++)
        s += f->ker->k[i] * f->y[(f->pos + i) % n];
    *res = s / f->sum;
    return 1;
}

int main(int argc, char *argv[])
{
    int set = 3, passes = 1;

    if (argc > 1)
        set = atoi(argv[1]);
    if (argc > 2)
        passes = atoi(argv[2]);
    if (set < 0 || set >= NSETS) {
        fprintf(stderr, "Номер набора должен быть от 0 до %d\n", NSETS - 1);
        for (int i = 0; i < NSETS; i++)
            fprintf(stderr, "  %d - %s\n", i, kernels[i].name);
        return 1;
    }
    if (passes < 1)
        passes = 1;
    if (passes > MAXPASS)
        passes = MAXPASS;

    /* сообщения - в stderr, чтобы не смешивать их с данными в stdout */
    fprintf(stderr, "filter: %s, проходов: %d\n", kernels[set].name, passes);

    FILTER f[MAXPASS];
    for (int i = 0; i < passes; i++)
        filter_init(&f[i], &kernels[set]);

    double x;
    char line[256];
    while (fgets(line, sizeof(line), stdin) != NULL) {
        if (sscanf(line, "%lf", &x) != 1)
            continue;                    /* пропускаем мусор */
        int ok = 1;
        for (int i = 0; i < passes && ok; i++)
            ok = filter_step(&f[i], x, &x);
        if (ok) {
            printf("%lf\n", x);
            fflush(stdout);              /* сразу отдаём данные в конвейер */
        }
    }
    return 0;
}
