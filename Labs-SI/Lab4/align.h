/*
 * Общий модуль для cyr2lat и lat2cyr:
 * разбивка строки на слова, подсчёт длины слов и
 * выравнивание текста по правой границе столбца.
 */
#ifndef ALIGN_H
#define ALIGN_H

#include <stdio.h>

#define DEFAULT_WIDTH 72        /* ширина столбца по умолчанию */
#define MAXLINE       8192

/* Статистика по словам одного файла */
typedef struct {
    long words;                 /* количество слов */
    long chars;                 /* суммарное количество символов в словах */
    int  longest;               /* длина самого длинного слова */
} WORDSTAT;

/* Разбить строку line на слова (разделители - пробелы и табуляции),
   для каждого слова подсчитать число символов и вывести слова в out
   строками не длиннее width, выровненными по правому краю.
   Пустая строка выводится как пустая (граница абзаца). */
void align_line(FILE *out, const char *line, int width, WORDSTAT *st);

/* Разбор параметров: [-w ширина] файлы...
   Возвращает индекс первого имени файла в argv. */
int parse_width(int argc, char *argv[], int *width);

#endif
